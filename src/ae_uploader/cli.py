@cli.command()
@click.argument('data_directory', type=click.Path(exists=True))
@click.option('--token', '-t', help='Invenio access token', envvar='INVENIO_TOKEN')
@click.option('--url', '-u', help='Invenio base URL', envvar='INVENIO_URL')
@click.option('--namespace', '-n', help='Custom field namespace', 
              envvar='CUSTOM_FIELD_NAMESPACE', default='domain')
@click.option('--metadata', '-m', 
              type=click.Path(exists=True),
              help='Path to metadata.json (default: looks in data_directory)')
@click.option('--no-zip', is_flag=True, 
              help='Upload files individually instead of as a zip archive')
@click.option('--draft-only', is_flag=True,
              help='Create draft but do not publish')
@click.option('--env-file', type=click.Path(exists=True),
              help='Path to .env file with INVENIO_TOKEN and INVENIO_URL')
@click.option('--save-credentials', is_flag=True,
              help='Save credentials to .env file in current directory')
@click.option('--schema', '-s', type=click.Path(exists=True),
              help='Path to custom JSON schema file')
@click.option('--insecure', is_flag=True, help='Disable SSL verification (not recommended)')

def upload(data_directory: str, 
           token: Optional[str],
           url: Optional[str],
           namespace: str,
           metadata: Optional[str],
           no_zip: bool,
           draft_only: bool,
           env_file: Optional[str],
           save_credentials: bool,
           schema: Optional[str],
           insecure: bool):
    """
    Upload a dataset directory to Invenio-RDM.
    
    Example:
        ae-upload upload ./my_simulation_data --token YOUR_TOKEN --url https://invenio.example.org
        
    The command will:
    1. Look for metadata.json in the data directory
    2. Validate the metadata against the CFD schema
    3. Create a draft record in Invenio-RDM
    4. Upload all files from the directory
    5. Publish the record (unless --draft-only is specified)
    """
    # Load environment file if specified
    if env_file:
        load_dotenv(env_file)
    else:
        load_dotenv()  # Load from .env in current directory if it exists
    
    # Check for required credentials - try env vars first, then prompt
    if not url:
        url = os.environ.get('INVENIO_URL')
    if not token:
        token = os.environ.get('INVENIO_TOKEN')
    
    # Prompt for URL if not provided
    if not url:
        url = click.prompt('Invenio-RDM instance URL', 
                          type=str,
                          default='https://data.ae.ic.ac.uk')

    url = url.rstrip('/')
    if url.endswith('/api'):
        url = url[:-4]
    
    # Prompt for token if not provided (hide input for security)
    if not token:
        click.echo("\nYou can get an access token from your Invenio profile:")
        click.echo(f"  {url}/account/settings/applications/tokens/new/")
        token = click.prompt('\nInvenio access token', 
                           type=str,
                           hide_input=True)
    
    # Save credentials if requested
    if save_credentials and url and token:
        env_path = Path('.env')
        if env_path.exists():
            if click.confirm('\n.env file already exists. Overwrite?', default=False):
                _save_credentials(env_path, url, token, namespace)
        else:
            _save_credentials(env_path, url, token, namespace)
            click.echo(f"[OK] Credentials saved to {env_path.absolute()}")
    
    # Find metadata file
    data_path = Path(data_directory)
    
    if metadata:
        metadata_path = Path(metadata)
    else:
        metadata_path = data_path / "metadata.json"
    
    if not metadata_path.exists():
        click.echo(f"[ERROR] metadata.json not found in {data_path}", err=True)
        click.echo("   Use --metadata to specify a different location", err=True)
        sys.exit(1)
    
    click.echo(f"[INFO] Validating metadata from {metadata_path}...")
    
    # Load custom schema if provided
    custom_schema = None
    if schema:
        try:
            with open(schema, 'r') as f:
                custom_schema = json.load(f)
            click.echo(f"[INFO] Using custom schema from {schema}")
        except Exception as e:
            click.echo(f"[ERROR] Failed to load custom schema: {e}", err=True)
            sys.exit(1)

    # Validate metadata
    try:
        is_valid, errors, hints = validate_with_hints(
            json.loads(metadata_path.read_text()),
            schema=custom_schema
        )
        
        if not is_valid:
            click.echo("[FAILED] Validation failed:", err=True)
            for error in errors:
                click.echo(f"   - {error}", err=True)
            
            if hints:
                click.echo("\n[HINTS]", err=True)
                for hint in hints:
                    click.echo(f"   - {hint}", err=True)
            
            sys.exit(1)
        
        click.echo("[OK] Metadata is valid!")
        
    except json.JSONDecodeError as e:
        click.echo(f"[ERROR] Invalid JSON in metadata file: {e}", err=True)
        sys.exit(1)
    except Exception as e:
        click.echo(f"[ERROR] Validation error: {e}", err=True)
        sys.exit(1)
    
    # Load metadata for upload
    metadata_dict = json.loads(metadata_path.read_text())
    
    # Initialize Invenio client
    click.echo(f"\n[INFO] Connecting to {url}...")
    client = InvenioClient(url, token, namespace)

    # Apply the insecure flag
    if insecure:
        client.session.verify = False
        click.echo("[WARNING] SSL verification is disabled. This is not recommended.", err=True)
    
    if not client.test_connection():
        click.echo("[ERROR] Cannot connect to Invenio instance", err=True)
        click.echo("   Check your URL and token", err=True)
        sys.exit(1)
    
    click.echo("[OK] Connected!")
    
    # Create draft
    click.echo("\n[INFO] Creating draft record...")
    try:
        draft = client.create_draft(metadata_dict)
        draft_id = draft['id']
        click.echo(f"[OK] Draft created with ID: {draft_id}")
    except Exception as e:
        click.echo(f"[ERROR] Error creating draft: {e}", err=True)
        sys.exit(1)
    
    # Check directory size
    dir_size = _get_directory_size(data_path)
    click.echo(f"\n[INFO] Directory size: {_format_bytes(dir_size)}")
    
    # Default to individual file upload (matching legacy script behavior)
    # Only use zip for very large datasets where it's explicitly beneficial
    if not no_zip:
        no_zip = True  # Default to individual files
    
    # Upload files
    click.echo(f"\n[INFO] Uploading files from {data_path}...")
    try:
        uploaded = client.upload_directory(
            draft_id, 
            str(data_path),
            create_zip=not no_zip
        )
        click.echo(f"[OK] Uploaded {len(uploaded)} file(s)")
    except Exception as e:
        click.echo(f"[ERROR] Error uploading files: {e}", err=True)
        sys.exit(1)
    
    # Publish or keep as draft
    if draft_only:
        click.echo(f"\n[OK] Draft created successfully!")
        click.echo(f"   View at: {url}/uploads/{draft_id}")
    else:
        click.echo("\n[INFO] Publishing record...")
        try:
            record = client.publish_draft(draft_id)
            record_id = record['id']
            click.echo("[OK] Record published successfully!")
            click.echo(f"   DOI: {record.get('doi', 'Pending')}")
            click.echo(f"   View at: {url}/records/{record_id}")
        except Exception as e:
            click.echo(f"[ERROR] Error publishing record: {e}", err=True)
            click.echo(f"   Draft saved at: {url}/uploads/{draft_id}", err=True)
            sys.exit(1)


@cli.command()
@click.argument('metadata_file', type=click.Path(exists=True))
@click.option('--verbose', '-v', is_flag=True, help='Show detailed validation errors')
@click.option('--schema', '-s', type=click.Path(exists=True),
              help='Path to custom JSON schema file')
def validate(metadata_file: str, verbose: bool, schema: Optional[str]):
    """
    Validate a metadata JSON file against the schema.
    
    Example:
        ae-upload validate metadata.json
        ae-upload validate metadata.json --schema my_schema.json
    """
    click.echo(f"[INFO] Validating {metadata_file}...")
    
    try:
        metadata_path = Path(metadata_file)
        metadata = json.loads(metadata_path.read_text())
        
        custom_schema = None
        if schema:
            with open(schema, 'r') as f:
                custom_schema = json.load(f)
            click.echo(f"[INFO] Using custom schema from {schema}")

        is_valid, errors, hints = validate_with_hints(metadata, schema=custom_schema)
        
        if is_valid:
            click.echo("[OK] Metadata is valid!")
            
            # Show summary
            if verbose:
                click.echo("\nSummary:")
                click.echo(f"  Title: {metadata.get('title', 'N/A')}")
                domain = metadata.get('domain', {})
                click.echo(f"  Discipline: {domain.get('discipline', 'N/A')}")
                click.echo(f"  Creators: {len(metadata.get('creators', []))}")
        else:
            click.echo("[FAILED] Validation failed:", err=True)
            click.echo()
            
            for error in errors:
                click.echo(f"  - {error}", err=True)
            
            if hints:
                click.echo("\n[HINTS]")
                for hint in hints:
                    click.echo(f"  - {hint}")
            
            sys.exit(1)
            
    except json.JSONDecodeError as e:
        click.echo(f"[ERROR] Invalid JSON in file: {e}", err=True)
        sys.exit(1)
    except FileNotFoundError:
        click.echo(f"[ERROR] File not found: {metadata_file}", err=True)
        sys.exit(1)
    except Exception as e:
        click.echo(f"[ERROR] {e}", err=True)
        sys.exit(1)


