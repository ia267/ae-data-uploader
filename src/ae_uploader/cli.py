@cli.command()
@click.option('--insecure', is_flag=True, help='Disable SSL verification (not recommended)')
def configure(insecure: bool):
    """
    Configure Invenio-RDM credentials interactively.
    
    This will prompt for your Invenio instance URL and access token,
    then save them to a .env file in the current directory.
    
    Example:
        ae-upload configure
        ae-upload configure --insecure
    """
    click.echo("=" * 50)
    click.echo("Invenio-RDM Credentials Setup")
    click.echo("=" * 50)
    
    # Check if .env already exists
    env_path = Path('.env')
    if env_path.exists():
        click.echo("\n[WARNING] .env file already exists in current directory")
        if not click.confirm('Overwrite existing credentials?', default=False):
            click.echo("Configuration cancelled.")
            return
    
    # Prompt for URL
    click.echo("\nStep 1: Invenio-RDM Instance URL")
    click.echo("  Example: https://data.ae.ic.ac.uk")
    url = click.prompt('\nEnter URL', type=str)
    
    # Clean up URL
    url = url.rstrip('/')
    if url.endswith('/api'):
        url = url[:-4]
    
    # Prompt for token
    click.echo("\nStep 2: Access Token")
    click.echo("  You can create a token at:")
    click.echo(f"  {url}/account/settings/applications/tokens/new/")
    click.echo("\n  The token should have 'deposit:write' permissions")
    token = click.prompt('\nEnter access token', type=str, hide_input=True)
    
    # Confirm token (re-enter for safety)
    token_confirm = click.prompt('Confirm access token', type=str, hide_input=True)
    
    if token != token_confirm:
        click.echo("\n[ERROR] Tokens don't match. Please try again.", err=True)
        sys.exit(1)
    
    # Prompt for custom field namespace
    click.echo("\nStep 3: Custom Field Namespace (optional)")
    click.echo("  The namespace for domain-specific metadata in Invenio")
    click.echo("  This must match your Invenio configuration")
    namespace = click.prompt('\nEnter namespace', type=str, default='domain', show_default=True)
    
    # Test connection
    click.echo("\n[INFO] Testing connection...")
    try:
        client = InvenioClient(url, token, namespace)

        if insecure:
            client.session.verify = False
            click.echo("[WARNING] SSL verification disabled for connection test")
        try:
            resp = client.session.get(f"{client.base_url}/api/records")
            if resp.status_code in [200, 403]:
                click.echo("[OK] Connection successful!")
            else:
                click.echo(f"[WARNING] Server returned status code: {resp.status_code}")
                click.echo("Check that your URL is correct (should be the base URL, not /api)")
        except Exception as e:
            click.echo(f"[WARNING] Connection failed: {e}")
            click.echo("Check your network connection and URL typo.")

    except Exception as e:
        click.echo(f"[WARNING] Connection test failed: {e}")
        if not click.confirm('\nSave credentials anyway?', default=True):
            click.echo("Configuration cancelled.")
            return
    
    # Save credentials
    _save_credentials(env_path, url, token, namespace)
    click.echo(f"\n[OK] Credentials saved to {env_path.absolute()}")
    click.echo("\nYou can now run commands without --token and --url options:")
    click.echo("  ae-upload generate numerical")
    click.echo("  ae-upload upload ./my_data")


